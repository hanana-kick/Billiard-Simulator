import { spawnSync } from 'node:child_process';
import { mkdir, copyFile, readFile, writeFile, chmod } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, isAbsolute } from 'node:path';
import { createHash } from 'node:crypto';
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(process.argv[2] || resolve(here, '../../artifacts/wasm-gpu-runtime.wasm'));
const cargo = process.env.CARGO || 'cargo';
const result = spawnSync(cargo, ['build', '--manifest-path', resolve(here, 'Cargo.toml'), '--target', 'wasm32-unknown-unknown', '--release', '--offline', '--locked', '--target-dir', resolve(here, 'target')], { stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) throw new Error(`WASM scheduler build failed (${result.status})`);
await mkdir(dirname(out), { recursive: true });
await copyFile(resolve(here, 'target/wasm32-unknown-unknown/release/billiard_wasm_gpu_runtime.wasm'), out);
await chmod(out, 0o644);
const bytes = await readFile(out);
const module = await WebAssembly.compile(bytes);
const imports = WebAssembly.Module.imports(module);
if (imports.length !== 1 || imports[0].module !== 'bridge' || imports[0].name !== 'submit' || imports[0].kind !== 'function') throw new Error('Unexpected WASM imports');
const expected = ['memory', 'abi_version', 'input_ptr', 'capacity', 'max_chunk', 'configure', 'load', 'start', 'step', 'commit', 'cancel', 'lose', 'dispose', 'state', 'generation', 'cursor', 'repeats_left', 'stream_len'];
const exports = WebAssembly.Module.exports(module);
for (const name of expected) if (!exports.some(e => e.name === name && e.kind === (name === 'memory' ? 'memory' : 'function'))) throw new Error(`Missing ABI export ${name}`);
const sha256 = buffer => createHash('sha256').update(buffer).digest('hex');
const sourceSha256 = {};
for (const name of ['Cargo.toml', 'Cargo.lock', 'src/lib.rs', 'build.mjs']) sourceSha256[name] = sha256(await readFile(resolve(here, name)));
const version = (executable, args) => {
  const result = spawnSync(executable, args, { encoding: 'utf8' });
  if (result.error || result.status !== 0) throw new Error(`Cannot record toolchain version: ${executable}`);
  return result.stdout.trim();
};
const provenance = { schema: 'billiard-wasm-gpu-build-v1', abiVersion: 1, target: 'wasm32-unknown-unknown', profile: 'release', offline: true, locked: true, byteLength: bytes.length, sha256: sha256(bytes), sourceSha256, cargoVersion: version(cargo, ['--version']), rustcVersion: version(isAbsolute(cargo) ? resolve(dirname(cargo), 'rustc') : 'rustc', ['--version', '--verbose']), imports, exports };
await writeFile(`${out}.build.json`, `${JSON.stringify(provenance, null, 2)}\n`);
console.log(out);
